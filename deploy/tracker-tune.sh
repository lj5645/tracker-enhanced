#!/usr/bin/env bash
# ============================================================
# tracker-tune.sh — BT Tracker 服务器内核/网络一键调优
#
# 完整说明见 docs/performance-tuning.md。
#
# 用法:
#   tracker-tune.sh apply                  # 应用全部优化（幂等，可重复执行）
#   tracker-tune.sh status                 # 查看参数与运行状态
#   tracker-tune.sh set <参数> <值>         # 微调单个参数并持久化
#   tracker-tune.sh notrack-add <端口>      # 新增免 conntrack 跟踪端口
#   tracker-tune.sh notrack-remove <端口>   # 移除免跟踪端口
#   tracker-tune.sh rollback               # 回滚到优化前默认值
#
# 注意:
#   - 需要 root 权限
#   - NOTRACK 规则假定 tracker 直接监听宿主机端口，且该端口不做
#     DNAT/端口映射（Docker -p 映射、iptables DNAT 会因此失效）
#   - 与 /etc/sysctl.conf 中重复且取值不同的条目会相互覆盖，
#     请按文档「配置冲突」一节统一到一处
# ============================================================
set -uo pipefail

SYSCTL_FILE="/etc/sysctl.d/99-conntrack.conf"
CONF_DIR="/etc/tracker-tune"
PARAMS_FILE="$CONF_DIR/params.conf"
PORTS_FILE="$CONF_DIR/ports.conf"
NOTRACK_SCRIPT="/usr/local/sbin/tracker-notrack.sh"
NOTRACK_UNIT="/etc/systemd/system/tracker-notrack.service"
CONNTRACK_UNIT="/etc/systemd/system/conntrack-tune.service"
MODPROBE_FILE="/etc/modprobe.d/nf_conntrack.conf"

# 调优项（顺序即写入 sysctl.d 的顺序）
ORDER=(
  "net.netfilter.nf_conntrack_max"
  "net.netfilter.nf_conntrack_tcp_timeout_established"
  "net.core.rmem_max"
  "net.core.wmem_max"
  "net.core.netdev_max_backlog"
  "net.core.somaxconn"
  "net.ipv4.tcp_max_syn_backlog"
  "net.ipv4.tcp_max_tw_buckets"
  "net.ipv4.tcp_fin_timeout"
  "net.ipv4.tcp_tw_reuse"
  "net.ipv4.ip_local_port_range"
)

# 优化后推荐值（首次生成 params.conf 时使用）
declare -A TUNED=(
  ["net.netfilter.nf_conntrack_max"]="4194304"
  ["net.netfilter.nf_conntrack_tcp_timeout_established"]="86400"
  ["net.core.rmem_max"]="16777216"
  ["net.core.wmem_max"]="16777216"
  ["net.core.netdev_max_backlog"]="65535"
  ["net.core.somaxconn"]="65535"
  ["net.ipv4.tcp_max_syn_backlog"]="65535"
  ["net.ipv4.tcp_max_tw_buckets"]="262144"
  ["net.ipv4.tcp_fin_timeout"]="15"
  ["net.ipv4.tcp_tw_reuse"]="1"
  ["net.ipv4.ip_local_port_range"]="10240 65535"
)

# 优化前默认值（rollback 时使用）
declare -A BASELINE=(
  ["net.netfilter.nf_conntrack_max"]="262144"
  ["net.netfilter.nf_conntrack_tcp_timeout_established"]="432000"
  ["net.core.rmem_max"]="212992"
  ["net.core.wmem_max"]="212992"
  ["net.core.netdev_max_backlog"]="1000"
  ["net.core.somaxconn"]="4096"
  ["net.ipv4.tcp_max_syn_backlog"]="1024"
  ["net.ipv4.tcp_max_tw_buckets"]="65536"
  ["net.ipv4.tcp_fin_timeout"]="60"
  ["net.ipv4.tcp_tw_reuse"]="2"
  ["net.ipv4.ip_local_port_range"]="32768 60999"
)

# ---------- 基础函数 ----------
need_root() {
  if [ "$(id -u)" -ne 0 ]; then
    echo "错误：请使用 root 运行" >&2
    exit 1
  fi
}

norm() { printf '%s' "$1" | tr '\t' ' ' | sed 's/  */ /g'; }

init_conf() {
  mkdir -p "$CONF_DIR"
  if [ ! -f "$PARAMS_FILE" ]; then
    : > "$PARAMS_FILE"
    for ik in "${ORDER[@]}"; do
      echo "$ik=${TUNED[$ik]}" >> "$PARAMS_FILE"
    done
  fi
  if [ ! -f "$PORTS_FILE" ]; then
    echo "6969" > "$PORTS_FILE"
  fi
}

param_get() {
  grep -m1 "^$1=" "$PARAMS_FILE" 2>/dev/null | cut -d= -f2-
}

write_sysctl() {
  {
    echo "# === BT Tracker / network tuning (managed by tracker-tune.sh) ==="
    echo "# 修改请用: tracker-tune.sh set <参数> <值>"
    echo "# 说明文档: docs/performance-tuning.md"
    for pk in "${ORDER[@]}"; do
      pv=$(param_get "$pk")
      [ -z "$pv" ] && pv="${TUNED[$pk]}"
      echo "$pk = $pv"
    done
  } > "$SYSCTL_FILE"
}

apply_runtime() {
  modprobe nf_conntrack 2>/dev/null || true
  while IFS= read -r rline; do
    case "$rline" in \#*|"") continue ;; esac
    rk="${rline%%=*}"
    rv="${rline#*=}"
    if sysctl -w "$rk=$rv" >/dev/null 2>&1; then
      :
    else
      echo "  ! 无法应用 $rk=$rv"
    fi
  done < "$PARAMS_FILE"

  # hashsize 建议为 conntrack_max 的 1/4（内核默认规则），最大支持 2^22
  echo "options nf_conntrack hashsize=1048576" > "$MODPROBE_FILE"
  echo 1048576 > /sys/module/nf_conntrack/parameters/hashsize 2>/dev/null || true
}

generate_notrack() {
  {
    echo '#!/bin/bash'
    echo '# Generated by tracker-tune.sh - do not edit by hand'
    while IFS= read -r np; do
      [ -z "$np" ] && continue
      for proto in tcp udp; do
        echo "iptables -t raw -C PREROUTING -p $proto --dport $np -j NOTRACK 2>/dev/null || iptables -t raw -I PREROUTING -p $proto --dport $np -j NOTRACK"
        echo "iptables -t raw -C OUTPUT -p $proto --sport $np -j NOTRACK 2>/dev/null || iptables -t raw -I OUTPUT -p $proto --sport $np -j NOTRACK"
        echo "ip6tables -t raw -C PREROUTING -p $proto --dport $np -j NOTRACK 2>/dev/null || ip6tables -t raw -I PREROUTING -p $proto --dport $np -j NOTRACK 2>/dev/null || true"
        echo "ip6tables -t raw -C OUTPUT -p $proto --sport $np -j NOTRACK 2>/dev/null || ip6tables -t raw -I OUTPUT -p $proto --sport $np -j NOTRACK 2>/dev/null || true"
      done
    done < "$PORTS_FILE"
    echo 'exit 0'
  } > "$NOTRACK_SCRIPT"
  chmod +x "$NOTRACK_SCRIPT"
}

install_units() {
  cat > "$NOTRACK_UNIT" <<'UNIT'
[Unit]
Description=Exclude BT tracker ports from conntrack
After=network-online.target docker.service
Wants=network-online.target

[Service]
Type=oneshot
RemainAfterExit=yes
ExecStart=/usr/local/sbin/tracker-notrack.sh

[Install]
WantedBy=multi-user.target
UNIT

  cat > "$CONNTRACK_UNIT" <<'UNIT'
[Unit]
Description=Apply conntrack tuning after netfilter is loaded
After=network-online.target docker.service
Wants=network-online.target

[Service]
Type=oneshot
RemainAfterExit=yes
ExecStart=/usr/sbin/sysctl -p /etc/sysctl.d/99-conntrack.conf

[Install]
WantedBy=multi-user.target
UNIT

  systemctl daemon-reload
  systemctl enable tracker-notrack.service >/dev/null 2>&1
  systemctl enable conntrack-tune.service >/dev/null 2>&1
  systemctl restart tracker-notrack.service
  systemctl restart conntrack-tune.service
}

# ---------- 子命令 ----------
cmd_apply() {
  need_root
  init_conf
  write_sysctl
  apply_runtime
  generate_notrack
  install_units
  echo "已应用全部优化。"
  echo ""
  cmd_status
}

cmd_status() {
  init_conf
  echo "=== 内核参数 ==="
  printf "%-58s %14s %14s %s\n" "参数" "期望" "当前" "结果"
  local bad=0
  local k
  for k in "${ORDER[@]}"; do
    local want cur res
    want=$(param_get "$k")
    [ -z "$want" ] && want="${TUNED[$k]}"
    cur=$(sysctl -n "$k" 2>/dev/null || echo "-")
    cur=$(norm "$cur")
    want=$(norm "$want")
    if [ "$cur" = "$want" ]; then
      res="OK"
    else
      res="不一致"
      bad=$((bad + 1))
    fi
    printf "%-58s %14s %14s %s\n" "$k" "$want" "$cur" "$res"
  done

  echo ""
  echo "=== conntrack ==="
  local c m
  c=$(sysctl -n net.netfilter.nf_conntrack_count 2>/dev/null || echo 0)
  m=$(sysctl -n net.netfilter.nf_conntrack_max 2>/dev/null || echo 1)
  printf "条目: %s / %s (%s%%)\n" "$c" "$m" "$(awk -v a="$c" -v b="$m" 'BEGIN { if (b > 0) printf "%.1f", a * 100 / b; else print "0.0" }')"
  printf "table full 累计: %s\n" "$(dmesg 2>/dev/null | grep -c 'table full')"
  printf "hashsize: %s\n" "$(cat /sys/module/nf_conntrack/parameters/hashsize 2>/dev/null || echo '-')"

  echo ""
  echo "=== NOTRACK ==="
  printf "免跟踪端口: %s\n" "$(tr '\n' ' ' < "$PORTS_FILE")"
  local pp pn
  for pp in $(cat "$PORTS_FILE"); do
    pn=$(iptables -t raw -L PREROUTING -n -v 2>/dev/null | grep -c "dpt:$pp ")
    printf "  port %-6s PREROUTING 命中规则 %s 条\n" "$pp" "$pn"
  done

  echo ""
  echo "=== Tracker ==="
  local tport
  tport=$(head -1 "$PORTS_FILE" 2>/dev/null || echo 6969)
  printf "并发连接: %s\n" "$(ss -tan 2>/dev/null | awk -v p=":$tport" '$4 ~ p"$" {c++} END {print c+0}')"
  ps -o pid,%cpu,%mem,rss,cmd -p $(pgrep -d, -f aquatic 2>/dev/null) 2>/dev/null | head -5

  echo ""
  echo "=== 服务 ==="
  local u en ac
  for u in tracker-notrack.service conntrack-tune.service; do
    en=$(systemctl is-enabled "$u" 2>/dev/null | head -1)
    ac=$(systemctl is-active "$u" 2>/dev/null | head -1)
    [ -z "$en" ] && en="-"
    [ -z "$ac" ] && ac="-"
    printf "%-30s %-10s %s\n" "$u" "$en" "$ac"
  done

  if [ "$bad" -gt 0 ]; then
    echo ""
    echo "提示：有 $bad 项与期望值不一致，可执行 'tracker-tune.sh apply' 重新应用。"
  fi
}

cmd_set() {
  need_root
  init_conf
  if [ $# -lt 2 ]; then
    echo "用法: tracker-tune.sh set <参数> <值>" >&2
    exit 1
  fi
  local k="$1" v="$2"
  case "$k" in
    net.*) ;;
    *) echo "错误：只允许修改 net.* 开头的内核参数" >&2; exit 1 ;;
  esac

  awk -v k="$k" -v v="$v" '{ if (index($0, k"=") == 1) print k"="v; else print }' \
    "$PARAMS_FILE" > "$PARAMS_FILE.tmp" && mv "$PARAMS_FILE.tmp" "$PARAMS_FILE"

  write_sysctl
  if sysctl -w "$k=$v" >/dev/null 2>&1; then
    echo "已设置 $k = $v（已持久化）"
  else
    echo "运行时设置失败: $k=$v（已写入配置文件，重启后生效）" >&2
    exit 1
  fi
}

cmd_notrack_add() {
  need_root
  init_conf
  local port="${1:-}"
  case "$port" in
    ''|*[!0-9]*) echo "错误：端口必须是数字" >&2; exit 1 ;;
  esac
  grep -qx "$port" "$PORTS_FILE" || echo "$port" >> "$PORTS_FILE"
  generate_notrack
  systemctl restart tracker-notrack.service 2>/dev/null || bash "$NOTRACK_SCRIPT"
  echo "已加入免跟踪端口: $port"
}

cmd_notrack_remove() {
  need_root
  init_conf
  local port="${1:-}"
  local proto
  for proto in tcp udp; do
    iptables -t raw -D PREROUTING -p "$proto" --dport "$port" -j NOTRACK 2>/dev/null || true
    iptables -t raw -D OUTPUT -p "$proto" --sport "$port" -j NOTRACK 2>/dev/null || true
    ip6tables -t raw -D PREROUTING -p "$proto" --dport "$port" -j NOTRACK 2>/dev/null || true
    ip6tables -t raw -D OUTPUT -p "$proto" --sport "$port" -j NOTRACK 2>/dev/null || true
  done
  grep -vx "$port" "$PORTS_FILE" > "$PORTS_FILE.tmp" || true
  mv "$PORTS_FILE.tmp" "$PORTS_FILE"
  generate_notrack
  systemctl restart tracker-notrack.service 2>/dev/null || true
  echo "已移除免跟踪端口: $port"
}

cmd_rollback() {
  need_root
  init_conf
  local ts bk
  ts=$(date +%Y%m%d-%H%M%S)
  bk="/root/network-backup/tracker-tune-$ts"
  mkdir -p "$bk"
  cp -a "$SYSCTL_FILE" "$bk/" 2>/dev/null || true
  cp -a "$PARAMS_FILE" "$bk/" 2>/dev/null || true
  cp -a "$PORTS_FILE" "$bk/" 2>/dev/null || true
  iptables-save > "$bk/iptables.rules" 2>/dev/null || true

  local p proto k
  for p in $(cat "$PORTS_FILE" 2>/dev/null); do
    for proto in tcp udp; do
      iptables -t raw -D PREROUTING -p "$proto" --dport "$p" -j NOTRACK 2>/dev/null || true
      iptables -t raw -D OUTPUT -p "$proto" --sport "$p" -j NOTRACK 2>/dev/null || true
      ip6tables -t raw -D PREROUTING -p "$proto" --dport "$p" -j NOTRACK 2>/dev/null || true
      ip6tables -t raw -D OUTPUT -p "$proto" --sport "$p" -j NOTRACK 2>/dev/null || true
    done
  done

  for k in "${ORDER[@]}"; do
    sysctl -w "$k=${BASELINE[$k]}" >/dev/null 2>&1 || true
  done

  systemctl disable --now tracker-notrack.service conntrack-tune.service >/dev/null 2>&1 || true
  rm -f "$NOTRACK_UNIT" "$CONNTRACK_UNIT" "$NOTRACK_SCRIPT" "$SYSCTL_FILE" "$MODPROBE_FILE"
  rm -rf "$CONF_DIR"
  systemctl daemon-reload

  echo "已回滚到优化前默认值。备份目录: $bk"
  echo "注意：hashsize 无法在线降回，重启后恢复默认。"
}

usage() {
  cat <<'EOF'
tracker-tune.sh — BT Tracker 服务器内核/网络调优

用法:
  tracker-tune.sh apply                   应用全部优化（幂等）
  tracker-tune.sh status                  查看参数与运行状态
  tracker-tune.sh set <参数> <值>           微调单个参数并持久化
  tracker-tune.sh notrack-add <端口>        新增免 conntrack 跟踪端口
  tracker-tune.sh notrack-remove <端口>     移除免跟踪端口
  tracker-tune.sh rollback                回滚到优化前默认值

示例:
  tracker-tune.sh set net.core.somaxconn 65535
  tracker-tune.sh set net.netfilter.nf_conntrack_max 2097152
  tracker-tune.sh notrack-add 6970
  tracker-tune.sh status

详细说明见 docs/performance-tuning.md
EOF
}

case "${1:-}" in
  apply)          shift; cmd_apply "$@" ;;
  status)         shift; cmd_status "$@" ;;
  set)            shift; cmd_set "$@" ;;
  notrack-add)    shift; cmd_notrack_add "$@" ;;
  notrack-remove) shift; cmd_notrack_remove "$@" ;;
  rollback)       shift; cmd_rollback "$@" ;;
  *)              usage ;;
esac
